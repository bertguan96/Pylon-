/// 按表做置位：table 里的 1 表示输入的第 1 位（最高位）
fn permute(input: u64, table: &[u8], in_bits: u32) -> u64 {
    let mut out = 0u64;
    for &pos in table {
        out = (out << 1) | ((input >> (in_bits - pos as u32)) & 1);
    }
    out
}

fn feistel(r: u32, subkey: u64) -> u32 {
    let expanded = permute(r as u64, &E, 32) ^ subkey;
    let mut out = 0u32;
    for i in 0..8 {
        let six = ((expanded >> (42 - i * 6)) & 0x3f) as usize;
        let row = ((six & 0x20) >> 4) | (six & 1);
        let col = (six >> 1) & 0xf;
        out = (out << 4) | SBOX[i][row * 16 + col] as u32;
    }
    permute(out as u64, &P, 32) as u32
}

fn subkeys(key: u64) -> [u64; 16] {
    let pc1 = permute(key, &PC1, 64);
    let mut c = ((pc1 >> 28) & 0x0fff_ffff) as u32;
    let mut d = (pc1 & 0x0fff_ffff) as u32;
    let mut out = [0u64; 16];
    for i in 0..16 {
        let s = SHIFTS[i];
        c = ((c << s) | (c >> (28 - s))) & 0x0fff_ffff;
        d = ((d << s) | (d >> (28 - s))) & 0x0fff_ffff;
        let cd = ((c as u64) << 28) | d as u64;
        out[i] = permute(cd, &PC2, 56);
    }
    out
}

pub fn des_encrypt_block(key: [u8; 8], block: [u8; 8]) -> [u8; 8] {
    let k = u64::from_be_bytes(key);
    let ks = subkeys(k);
    let m = permute(u64::from_be_bytes(block), &IP, 64);
    let mut l = (m >> 32) as u32;
    let mut r = m as u32;
    for &sk in ks.iter() {
        let next = l ^ feistel(r, sk);
        l = r;
        r = next;
    }
    // 16 轮结束后是 R16 L16（左右互换）再进 FP，这一步搞反会得到「看起来像乱码但
    // 只差一对半字节」的结果，是最容易蒙混过关的错法
    let pre = ((r as u64) << 32) | l as u64;
    permute(pre, &FP, 64).to_be_bytes()
}

fn reverse_bits(b: u8) -> u8 {
    b.reverse_bits()
}

/// 生成 VNC 认证响应：16 字节挑战 → 16 字节响应。
/// 密码只取前 8 字节，不足补 0（VNC 的历史遗留，服务端也是这么截的）。
pub fn vnc_auth_response(password: &str, challenge: &[u8]) -> Vec<u8> {
    debug_assert_eq!(challenge.len(), 16);
    let raw = password.as_bytes();
    let mut key = [0u8; 8];
    for i in 0..8 {
        key[i] = reverse_bits(*raw.get(i).unwrap_or(&0));
    }
    let mut out = Vec::with_capacity(16);
    let mut b0 = [0u8; 8];
    let mut b1 = [0u8; 8];
    b0.copy_from_slice(&challenge[0..8]);
    b1.copy_from_slice(&challenge[8..16]);
    out.extend_from_slice(&des_encrypt_block(key, b0));
    out.extend_from_slice(&des_encrypt_block(key, b1));
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// 教科书向量：key=133457799BBCDFF1, plain=0123456789ABCDEF → 85E813540F0AB405
    #[test]
    fn des_known_answer() {
        let key = [0x13, 0x34, 0x57, 0x79, 0x9b, 0xbc, 0xdf, 0xf1];
        let block = [0x01, 0x23, 0x45, 0x67, 0x89, 0xab, 0xcd, 0xef];
        let got = des_encrypt_block(key, block);
        assert_eq!(
            got,
            [0x85, 0xe8, 0x13, 0x54, 0x0f, 0x0a, 0xb4, 0x05]
        );
    }

    /// 全零挑战 + 密码 12345678：与 JS 侧自测向量一致，两边必须逐字节相同
    #[test]
    fn vnc_response_vector() {
        let challenge = [0u8; 16];
        let got = vnc_auth_response("12345678", &challenge);
        let expect = [
            0xd2u8, 0x9f, 0x6e, 0x7f, 0x04, 0x56, 0xf8, 0xde, 0xd2, 0x9f, 0x6e, 0x7f, 0x04, 0x56,
            0xf8, 0xde,
        ];
        assert_eq!(got.as_slice(), &expect);
    }
}
